#!/usr/bin/env python3
"""
Generates everything the Verilog testbench needs, using the Python model
(orientation_only.py) as the golden reference.  Pure Python, no packages needed.

Expected project layout:
    hw/orientation/rtl/     RTL  (orient_tan_table.svh is written here)
    hw/orientation/model/   orientation_only.py
    hw/orientation/tb/      tb_orient.sv
    hw/orientation/sim/     this script and the vectors

Files written:
    <rtl-dir>/orient_tan_table.svh   comparator constants used by orient_quantizer.sv
    <out-dir>/sim_params.svh         IMG_W / IMG_H / counts for the testbench
    <out-dir>/img.hex               test image, one byte per line (raster order)
    <out-dir>/kps.txt               keypoints "x y" pushed into the keypoint FIFO
    <out-dir>/expected_core.txt     every valid window:  x y m00 m10 m01 quadrant sector
    <out-dir>/expected_top.txt      keypoints that must come out:  x y quadrant sector

By default <out-dir> is the folder of this script (independent of the current
directory) and <rtl-dir> is ../rtl relative to it.

usage: python gen_vectors.py [--w 96] [--h 64] [--sectors 64] [--rounding paper|nearest]
                             [--frac-bits 8] [--seed 1] [--out-dir DIR] [--rtl-dir DIR]
"""
import argparse
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "model"))   # golden model lives in ../model

from orientation_only import HALF, OrientationModule, WINDOW


def make_image(w, h, rng):
    img = [[rng.randrange(256) for _ in range(w)] for _ in range(h)]
    # flat bright block next to a flat dark block: flat windows (m10 = m01 = 0 corner
    # case) and a hard step edge (largest |m10|) -> exercises register widths.
    bh, bw = 45, 45
    top, left = 8, 4
    if h >= top + bh and w >= left + 2 * bw:
        for y in range(top, top + bh):
            for x in range(left, left + bw):
                img[y][x] = 255
            for x in range(left + bw, left + 2 * bw):
                img[y][x] = 0
    return img


def write_tan_table(mod, n_sectors, rounding, path):
    consts = mod.tan_consts
    tc_w = max(c.bit_length() for c in consts)
    body = ", ".join(f"{tc_w}'d{c}" for c in reversed(consts))     # MSB = last comparator
    with open(path, "w") as f:
        f.write(f"// generated by gen_vectors.py: N_SECT={n_sectors}, rounding={rounding}, "
                f"frac_bits={mod.frac_bits}\n")
        f.write(f"localparam int TBL_NSECT = {n_sectors};\n")
        f.write(f"localparam int FRAC_BITS = {mod.frac_bits};\n")
        f.write(f"localparam int N_CMP     = {len(consts)};\n")
        f.write(f"localparam int TC_W      = {tc_w};\n")
        f.write(f"localparam logic [N_CMP*TC_W-1:0] TAN_TABLE = {{{body}}};\n")


def main():
    default_rtl = os.path.normpath(os.path.join(HERE, "..", "rtl"))
    ap = argparse.ArgumentParser()
    ap.add_argument("--w", type=int, default=96)
    ap.add_argument("--h", type=int, default=64)
    ap.add_argument("--sectors", type=int, default=64)
    ap.add_argument("--rounding", default="paper", choices=["paper", "nearest"])
    ap.add_argument("--frac-bits", type=int, default=8)
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--out-dir", default=HERE)
    ap.add_argument("--rtl-dir", default=default_rtl if os.path.isdir(default_rtl) else HERE)
    a = ap.parse_args()
    assert a.w > WINDOW and a.h > WINDOW
    out = lambda name: os.path.join(a.out_dir, name)

    rng = random.Random(a.seed)
    img = make_image(a.w, a.h, rng)
    mod = OrientationModule(a.sectors, a.rounding, a.frac_bits)
    write_tan_table(mod, a.sectors, a.rounding, os.path.join(a.rtl_dir, "orient_tan_table.svh"))

    # ---- every valid window ------------------------------------------------------
    res = mod.process_image(img)
    with open(out("expected_core.txt"), "w") as f:
        for r in res:
            f.write(f"{r.x} {r.y} {r.m00} {r.m10} {r.m01} {r.quadrant} {r.sector}\n")

    # ---- keypoints: valid ones, border ones (must be dropped) and duplicates ---------
    valid_pos = [(r.x, r.y) for r in res]
    kps = rng.sample(valid_pos, 60)
    kps += [(2, 3), (5, 40), (a.w - 3, a.h - 4), (a.w - 1, 10), (30, a.h - 2), (HALF - 1, HALF)]
    kps += rng.sample(kps[:60], 4)                     # duplicates -> "stale" pop path
    kps = sorted(kps, key=lambda p: (p[1], p[0]))      # raster order, as FAST/NMS delivers

    in_range = lambda p: HALF <= p[0] <= a.w - HALF - 1 and HALF <= p[1] <= a.h - HALF - 1
    unique = sorted({p for p in kps if in_range(p)}, key=lambda p: (p[1], p[0]))
    top_res = mod.process_image(img, keypoints=unique)

    with open(out("kps.txt"), "w") as f:
        for x, y in kps:
            f.write(f"{x} {y}\n")
    with open(out("expected_top.txt"), "w") as f:
        for r in top_res:
            f.write(f"{r.x} {r.y} {r.quadrant} {r.sector}\n")

    with open(out("img.hex"), "w") as f:
        for row in img:
            for p in row:
                f.write(f"{p:02x}\n")

    with open(out("sim_params.svh"), "w") as f:
        f.write(f"localparam int IMG_W = {a.w};\nlocalparam int IMG_H = {a.h};\n")
        f.write(f"localparam int N_SECT = {a.sectors};\n")
        f.write(f"localparam int N_WIN = {len(res)};\n")
        f.write(f"localparam int N_KP = {len(kps)};\nlocalparam int N_TOP = {len(top_res)};\n")

    print(f"image {a.w}x{a.h}, {len(res)} windows, {len(kps)} keypoints pushed "
          f"({len(top_res)} expected out), N_SECT={a.sectors}, rounding={a.rounding}")
    print(f"  vectors -> {a.out_dir}\n  orient_tan_table.svh -> {a.rtl_dir}")


if __name__ == "__main__":
    main()
